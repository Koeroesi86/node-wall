// No relative imports: scripts/generate-schemas.mts loads this file directly with Node's type stripping.

export interface ColumnInfo {
  name: string;
  type: string;
  notnull: number;
}

const INTERNAL_TABLES = ['knex_migrations', 'knex_migrations_lock'];

export const isApplicationTable = (name: string) => !INTERNAL_TABLES.includes(name) && !name.startsWith('sqlite_');

/** Follows the SQLite type affinity rules (https://sqlite.org/datatype3.html#determination_of_column_affinity). */
export const mapType = (declaredType: string): string => {
  const type = declaredType.toUpperCase();
  if (type.includes('INT')) return 'z.number().int()';
  if (/CHAR|CLOB|TEXT/.test(type)) return 'z.string()';
  if (type.includes('BLOB')) return 'z.instanceof(Buffer)';
  if (type === '') return 'z.unknown()';
  return 'z.number()';
};

export const mapColumn = ({ type, notnull }: ColumnInfo) => `${mapType(type)}${notnull ? '' : '.nullable()'}`;

export const toKebabCase = (value: string) => value.replace(/_/g, '-').toLowerCase();

const toPascalCase = (value: string) => value.split(/[_-]/).map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('');

export const schemaFileName = (table: string) => `${toKebabCase(table)}.ts`;

export const renderSchema = (table: string, columns: ColumnInfo[]) => {
  const name = toPascalCase(table);
  const fields = columns.map(column => `  ${JSON.stringify(column.name)}: ${mapColumn(column)},`).join('\n');
  return [
    '// Generated by `npm run generate:schemas` from the SQLite schema. Do not edit.',
    "import { z } from 'zod';",
    '',
    `export const ${name}Schema = z.object({`,
    fields,
    '});',
    '',
    `export type ${name} = z.infer<typeof ${name}Schema>;`,
    '',
  ].join('\n');
};

export const renderIndex = (tables: string[]) => [
  '// Generated by `npm run generate:schemas`. Do not edit.',
  ...tables.map(table => `export * from './${toKebabCase(table)}';`),
  '',
].join('\n');
