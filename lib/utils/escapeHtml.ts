/** Escapes text so it is safe inside HTML content and double/single quoted attributes. */
function escapeHtml(value: unknown = ''): string {
  return `${value}`
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export default escapeHtml;
